def symbol(name):
    with urllib.request.urlopen(SOURCE.format(name), timeout=20) as resp:
        svg = resp.read().decode()
    inner = re.search(r"<svg[^>]*>(.*)</svg>", svg, re.S).group(1)
    inner = re.sub(r"<!--.*?-->", "", inner, flags=re.S).strip()
    inner = re.sub(r"\s+", " ", inner)
    return f'<symbol id="{name}" viewBox="0 0 24 24">{inner}</symbol>'


def main():
    symbols = [symbol(n) for n in ICONS]
    OUT.write_text(
        f"<!-- Lucide {VERSION} (ISC license, https://lucide.dev/license); generated by "
        "scripts/vendor_icons.py — do not edit -->\n"
        '<svg xmlns="http://www.w3.org/2000/svg" fill="none" stroke="currentColor" '
        'stroke-width="2" stroke-linecap="round" stroke-linejoin="round">\n'
        + "\n".join(symbols)
        + "\n</svg>\n"
    )
    print(f"{OUT}: {len(symbols)} icons from lucide-static {VERSION}")


if __name__ == "__main__":
    main()
