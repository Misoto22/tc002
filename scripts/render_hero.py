"""Draw the README's hero banner, light and dark: the tc002 mark, the name, the one-line
description, and the clock itself showing a time in tc002's own pixel font.

Colours come from web/static/css/tokens.css (the light and dark :root blocks) and the
LED pixels from the Python renderer, so the banner stays in step with the UI and the
clock. Text is left-anchored at computed positions with a system font stack, because
GitHub's SVG sanitiser drops web fonts and does not always honour text-anchor.

    uv run python scripts/render_hero.py
"""

import re
import sys
from pathlib import Path

from tc002.render.canvas import HEIGHT, WIDTH, Canvas
from tc002.render.palette import LED

ROOT = Path(__file__).resolve().parent.parent
TOKENS = ROOT / "src/tc002/web/static/css/tokens.css"
OUT = ROOT / "docs"
W, H = 1640, 480  # 820 px wide in the README, at 2x
PITCH = 11  # LED spacing in the banner
FONT = "system-ui, -apple-system, 'Segoe UI', Helvetica, Arial, sans-serif"
NAME = "tc002"
LINES = ("Set up and run the Ulanzi TC002", "pixel clock from your Mac")


def tokens(theme):
    """The colour tokens of the light (first :root) or dark (:root[data-theme=dark]) block."""
    css = TOKENS.read_text()
    block = css if theme == "light" else css[css.index(':root[data-theme="dark"]') :]
    pick = {}
    for name in ("bg", "panel", "text", "muted", "accent", "border"):
        m = re.search(rf"--{name}: (#[0-9a-f]{{6}}|rgb\([^)]*\));", block)
        pick[name] = m.group(1)
    return pick


def led_frame():
    c = Canvas()
    c.text_centered(1, "14:32", LED["white"])
    for x in range(14, 38, 3):  # the seconds bar under the time, as the clock's own app
        c.set(x, 14, LED["orange"])
    return c


def _hex(value):
    return f"#{value:06x}"


def svg(theme):
    t = tokens(theme)
    panel_w, panel_h = WIDTH * PITCH + 56, HEIGHT * PITCH + 56
    px, py = W - panel_w - 96, (H - panel_h) // 2
    off = _hex(LED["grid"])
    dots = []
    frame = led_frame()
    for y in range(HEIGHT):
        for x in range(WIDTH):
            value = frame.px[y * WIDTH + x]
            cx, cy = px + 28 + x * PITCH + PITCH / 2, py + 28 + y * PITCH + PITCH / 2
            fill = _hex(value) if value else off
            dots.append(f'<circle cx="{cx:g}" cy="{cy:g}" r="4.2" fill="{fill}"/>')
    mark = (
        f'<g transform="translate(96 132) scale(3.2)">'
        f'<rect width="30" height="30" rx="8" fill="{t["text"]}"/>'
        f'<g fill="{t["bg"]}">'
        + "".join(f'<circle cx="{x}" cy="{y}" r="1.6"/>' for y in (12, 18) for x in (8, 13, 17))
        + f'</g><circle cx="22.5" cy="15" r="2.6" fill="{t["accent"]}"/></g>'
    )
    text = (
        f'<text x="226" y="214" font-family="{FONT}" font-size="76" font-weight="650" '
        f'letter-spacing="-1.5" fill="{t["text"]}">{NAME}</text>'
        + "".join(
            f'<text x="96" y="{300 + i * 46}" font-family="{FONT}" font-size="34" '
            f'fill="{t["muted"]}">{line}</text>'
            for i, line in enumerate(LINES)
        )
    )
    bezel = (
        f'<rect x="{px}" y="{py}" width="{panel_w}" height="{panel_h}" rx="26" '
        f'fill="{_hex(LED["panel"])}"/>'
        f'<rect x="{px + 0.5}" y="{py + 0.5}" width="{panel_w - 1}" height="{panel_h - 1}" '
        f'rx="26" fill="none" stroke="{t["border"]}" stroke-opacity="0.6"/>'
    )
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" width="{W}" height="{H}" '
        f'role="img" aria-label="tc002: set up and run the Ulanzi TC002 pixel clock from your Mac">'
        f"<!-- generated by scripts/render_hero.py; edit that, not this -->"
        f'<rect width="{W}" height="{H}" rx="28" fill="{t["bg"]}"/>'
        f"{mark}{text}{bezel}{''.join(dots)}</svg>\n"
    )


def main():
    for theme in ("light", "dark"):
        path = OUT / f"hero-{theme}.svg"
        path.write_text(svg(theme))
        print(f"wrote {path.relative_to(ROOT)} ({path.stat().st_size} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
