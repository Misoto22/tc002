import { assets } from "./assets.js";

// Small DOM toolkit: one element helper, Lucide icons from the local sprite, and the
// controls every page shares.

export function h(tag, props = {}, ...children) {
  const el = document.createElement(tag);
  for (const [key, value] of Object.entries(props)) {
    if (value === undefined || value === null || value === false) continue;
    if (key.startsWith("on")) el.addEventListener(key.slice(2).toLowerCase(), value);
    else if (key === "class") el.className = value;
    else if (key === "style") el.style.cssText = value; // CSSOM: allowed by the page's CSP
    else el.setAttribute(key, value === true ? "" : value);
  }
  for (const child of children.flat()) {
    if (child === null || child === undefined || child === false) continue;
    el.append(child instanceof Node ? child : document.createTextNode(String(child)));
  }
  return el;
}

const SVG = "http://www.w3.org/2000/svg";

// A design token's value (tokens.css), e.g. token("--radius"); ms("--normal") -> 200.
export const token = (name) => getComputedStyle(document.documentElement).getPropertyValue(name).trim();
export const ms = (name) => parseFloat(token(name)) || 0;

// Lucide icon by name, from /icons.svg (generated by scripts/vendor_icons.py).
export function icon(name, cls = "icon") {
  const svg = document.createElementNS(SVG, "svg");
  svg.setAttribute("class", cls);
  svg.setAttribute("aria-hidden", "true");
  const use = document.createElementNS(SVG, "use");
  use.setAttribute("href", `/icons.svg#${name}`);
  svg.append(use);
  return svg;
}

export function toggle(checked, onChange, { label, disabled } = {}) {
  return h("button", {
    class: "toggle", type: "button", role: "switch", "aria-checked": String(Boolean(checked)),
    "aria-label": label, disabled,
    onClick: (e) => {
      const next = e.currentTarget.getAttribute("aria-checked") !== "true";
      e.currentTarget.setAttribute("aria-checked", String(next));
      onChange(next);
    },
  });
}

export function segmented(options, value, onChange, label) {
  const group = h("div", { class: "segmented", role: "radiogroup", "aria-label": label });
  for (const [optValue, optLabel] of options) {
    group.append(h("button", {
      type: "button", role: "radio", "aria-checked": String(optValue === value),
      onClick: (e) => {
        for (const b of group.children) b.setAttribute("aria-checked", "false");
        e.currentTarget.setAttribute("aria-checked", "true");
        onChange(optValue);
      },
    }, optLabel));
  }
  return group;
}

export function slider(min, max, value, onChange, label) {
  const out = h("output", {}, value);
  const input = h("input", {
    type: "range", min, max, step: 1, value, "aria-label": label,
    onInput: (e) => { out.textContent = e.target.value; onChange(Number(e.target.value)); },
  });
  return h("div", { class: "slider" }, input, out);
}

export function select(options, value, onChange, label) {
  const el = h("select", { class: "field", "aria-label": label, onChange: (e) => onChange(e.target.value) });
  for (const [v, text] of options) el.append(h("option", { value: v, selected: String(v) === String(value) }, text));
  return h("div", { class: "select" }, el, icon("chevron-down", "icon select-caret"));
}

// An app's icon: the official mark (or a Lucide glyph) listed in app-icons.json, drawn
// monochrome on a neutral tile like every other icon.
export function appIcon(key, size = "") {
  const spec = assets.icons[key];
  const tile = h("span", { class: `app-icon ${size}`.trim(), "aria-hidden": "true" });
  if (!spec) return tile;
  tile.append(icon(spec.symbol, spec.kind === "brand" ? "icon icon-brand" : "icon"));
  return tile;
}

// A settings row. `path` (e.g. "display.volume") lets the app mark unsaved rows.
export function row(title, hint, controls = [], { path, icon: ico, app, onFocus } = {}) {
  return h("div", { class: "row", "data-path": path, onFocusin: onFocus, onPointerdown: onFocus },
    app ? appIcon(app) : ico && h("span", { class: "row-icon" }, icon(ico)),
    h("div", { class: "row-text" },
      h("div", { class: "row-title" }, title),
      hint && h("div", { class: `row-hint${hint.warn ? " warn" : ""}` }, hint.text ?? hint)),
    h("div", { class: "row-control" }, ...[controls].flat()));
}

export const panel = (...rows) => h("div", { class: "panel" }, ...rows);
export const section = (...content) => h("div", { class: "section-title" }, ...content);

export function badge(text, tone) {
  return h("span", { class: `badge ${tone ?? ""}` }, h("span", { class: `dot ${tone ?? ""}` }), text);
}

export function button(label, onClick, { kind = "", ico, title, disabled } = {}) {
  return h("button", { class: `btn ${kind}`, type: "button", onClick, title, disabled, "aria-label": title },
    ico && icon(ico), label);
}

export function pageHead(title, description, ...actions) {
  return h("div", { class: "page-head" },
    h("div", {}, h("h1", {}, title), description && h("p", {}, description)),
    actions.length ? h("div", { class: "actions" }, ...actions) : null);
}

export function toast(title, detail, kind = "info") {
  const ico = { info: "circle-check", error: "circle-alert", warn: "triangle-alert" }[kind];
  const el = h("div", { class: `toast ${kind}`, role: kind === "error" ? "alert" : "status" },
    icon(ico), h("div", {}, title, detail && h("span", { class: "muted" }, detail)));
  document.getElementById("toasts").append(el);
  setTimeout(() => { el.classList.add("leaving"); setTimeout(() => el.remove(), ms("--normal")); },
    kind === "error" ? 8000 : 4000);
}

// Show a fixed popover under `anchor` (above it when there is no room below; right-aligned
// when it would overflow). It closes on an outside click, Escape, scroll or resize: a fixed
// layer cannot follow its anchor when the page moves, so it must not outlive the move.
// Returns close().
export function attachPopover(el, anchor, onClose) {
  document.body.append(el);
  const box = anchor.getBoundingClientRect();
  const gap = 6;
  const left = box.left + el.offsetWidth > innerWidth - 8 ? box.right - el.offsetWidth : box.left;
  const fitsBelow = box.bottom + gap + el.offsetHeight <= innerHeight - 8;
  el.style.left = `${Math.max(8, left)}px`;
  el.style.top = `${fitsBelow || box.top < el.offsetHeight + gap ? box.bottom + gap : box.top - gap - el.offsetHeight}px`;
  const outside = (e) => { if (!el.contains(e.target) && !anchor.contains(e.target)) close(); };
  const moved = (e) => { if (!(e.target instanceof Node) || !el.contains(e.target)) close(); };
  function close() {
    el.remove();
    document.removeEventListener("pointerdown", outside);
    document.removeEventListener("scroll", moved, true);
    window.removeEventListener("resize", moved);
    onClose?.();
  }
  setTimeout(() => document.addEventListener("pointerdown", outside));
  document.addEventListener("scroll", moved, true); // capture: #main scrolls, not the window
  window.addEventListener("resize", moved);
  el.addEventListener("keydown", (e) => { if (e.key === "Escape") { close(); anchor.focus(); } });
  return close;
}

// A popover menu of grouped items; closes on pick, or as attachPopover does.
export function menu(anchor, groups, onPick, emptyText) {
  document.querySelector(".menu")?.remove();
  const el = h("div", { class: "menu", role: "menu" });
  let close = () => {};
  for (const [label, items] of groups) {
    if (!items.length) continue;
    el.append(h("div", { class: "menu-label" }, label));
    for (const [value, text, ico, app] of items) {
      el.append(h("button", { type: "button", role: "menuitem", onClick: () => { close(); onPick(value); } },
        app ? appIcon(app, "sm") : ico && icon(ico), text));
    }
  }
  if (!el.querySelector("button")) el.append(h("div", { class: "menu-label" }, emptyText));
  close = attachPopover(el, anchor);
  el.querySelector("button")?.focus();
  el.addEventListener("keydown", (e) => {
    const items = [...el.querySelectorAll("button")];
    const i = items.indexOf(document.activeElement);
    if (e.key === "ArrowDown") { e.preventDefault(); items[(i + 1) % items.length]?.focus(); }
    if (e.key === "ArrowUp") { e.preventDefault(); items[(i - 1 + items.length) % items.length]?.focus(); }
  });
}

// Run a DOM update inside a View Transition when the browser can animate it. The update
// must never wait on the animation: if the transition has not started within 250 ms
// (background tab, busy renderer) it is skipped and the update runs anyway.
export function transition(update) {
  const reduce = matchMedia("(prefers-reduced-motion: reduce)").matches;
  if (!document.startViewTransition || reduce) return update();
  let done = false;
  const run = () => { if (!done) { done = true; update(); } };
  const vt = document.startViewTransition(run);
  setTimeout(() => { if (!done) { vt.skipTransition(); run(); } }, 250);
}
