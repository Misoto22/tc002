// Small DOM toolkit: one element helper, Lucide icons from the local sprite, and the
// controls every page shares.

export function h(tag, props = {}, ...children) {
  const el = document.createElement(tag);
  for (const [key, value] of Object.entries(props)) {
    if (value === undefined || value === null || value === false) continue;
    if (key.startsWith("on")) el.addEventListener(key.slice(2).toLowerCase(), value);
    else if (key === "class") el.className = value;
    else if (key === "style") el.style.cssText = value; // CSSOM: allowed by the page's CSP
    else el.setAttribute(key, value === true ? "" : value);
  }
  for (const child of children.flat()) {
    if (child === null || child === undefined || child === false) continue;
    el.append(child instanceof Node ? child : document.createTextNode(String(child)));
  }
  return el;
}

const SVG = "http://www.w3.org/2000/svg";

// A design token's value (tokens.css), e.g. token("--radius"); ms("--normal") -> 200.
export const token = (name) => getComputedStyle(document.documentElement).getPropertyValue(name).trim();
export const ms = (name) => parseFloat(token(name)) || 0;

// Lucide icon by name, from /icons.svg (generated by scripts/vendor_icons.py).
export function icon(name, cls = "icon") {
  const svg = document.createElementNS(SVG, "svg");
  svg.setAttribute("class", cls);
  svg.setAttribute("aria-hidden", "true");
  const use = document.createElementNS(SVG, "use");
  use.setAttribute("href", `/icons.svg#${name}`);
  svg.append(use);
  return svg;
}

export function toggle(checked, onChange, { label, disabled } = {}) {
  return h("button", {
    class: "toggle", type: "button", role: "switch", "aria-checked": String(Boolean(checked)),
    "aria-label": label, disabled,
    onClick: (e) => {
      const next = e.currentTarget.getAttribute("aria-checked") !== "true";
      e.currentTarget.setAttribute("aria-checked", String(next));
      onChange(next);
    },
  });
}

// A segmented control whose thumb can be dragged: it follows the pointer, and on release
// settles on the nearest option. Clicks and the arrow keys work as on any radio group.
export function segmented(options, value, onChange, label) {
  const thumb = h("span", { class: "segmented-thumb", "aria-hidden": "true" });
  const group = h("div", { class: "segmented", role: "radiogroup", "aria-label": label }, thumb);
  const buttons = options.map(([optValue, optLabel], i) => h("button", {
    type: "button", role: "radio", tabindex: optValue === value ? "0" : "-1",
    onClick: () => choose(i),
  }, optLabel));
  group.append(...buttons);
  let index = Math.max(0, options.findIndex(([v]) => v === value));
  let drag = null;

  function paint(at, chosen = Math.round(at)) {
    group.style.setProperty("--n", options.length);
    group.style.setProperty("--i", at);
    buttons.forEach((b, i) => {
      b.setAttribute("aria-checked", String(i === chosen));
      b.tabIndex = i === chosen ? 0 : -1;
    });
  }

  function choose(i) {
    const changed = i !== index;
    index = i;
    paint(i);
    if (changed) onChange(options[i][0]);
  }

  // pointer x -> fractional cell index under the thumb's centre
  const position = (e) => {
    const box = group.getBoundingClientRect();
    const cell = (box.width - 4) / options.length;
    return Math.min(options.length - 1, Math.max(0, (e.clientX - box.left - 2 - cell / 2) / cell));
  };

  group.addEventListener("pointerdown", (e) => {
    if (e.button !== 0) return;
    drag = { x: e.clientX, moved: false };
    group.setPointerCapture(e.pointerId);
  });
  group.addEventListener("pointermove", (e) => {
    if (!drag) return;
    if (!drag.moved && Math.abs(e.clientX - drag.x) < 3) return;
    drag.moved = true;
    group.classList.add("dragging");
    paint(position(e));
  });
  const release = (e) => {
    if (!drag) return;
    group.classList.remove("dragging");
    drag = null;
    if (e.type === "pointerup") choose(Math.round(position(e)));
    else paint(index);
  };
  group.addEventListener("pointerup", release);
  group.addEventListener("pointercancel", release);
  group.addEventListener("keydown", (e) => {
    const step = { ArrowRight: 1, ArrowDown: 1, ArrowLeft: -1, ArrowUp: -1 }[e.key];
    const jump = { Home: 0, End: options.length - 1 }[e.key];
    if (step === undefined && jump === undefined) return;
    e.preventDefault();
    choose(jump ?? (index + step + options.length) % options.length);
    buttons[index].focus();
  });
  paint(index);
  return group;
}

export function slider(min, max, value, onChange, label) {
  const out = h("output", {}, value);
  const input = h("input", {
    type: "range", min, max, step: 1, value, "aria-label": label,
    onInput: (e) => { out.textContent = e.target.value; onChange(Number(e.target.value)); },
  });
  return h("div", { class: "slider" }, input, out);
}

export function select(options, value, onChange, label) {
  const el = h("select", { class: "field", "aria-label": label, onChange: (e) => onChange(e.target.value) });
  for (const [v, text] of options) el.append(h("option", { value: v, selected: String(v) === String(value) }, text));
  return h("div", { class: "select" }, el, icon("chevron-down", "icon select-caret"));
}

// An app's icon: the official mark (or a Lucide glyph) listed in app-icons.json, drawn
// as a glyph with no tile behind it; the CSS colours the agents (data-app) by brand.
export function appIcon(key, size = "") {
  const spec = assets.icons[key];
  const tile = h("span", { class: `app-icon ${size}`.trim(), "data-app": key, "aria-hidden": "true" });
  if (!spec) return tile;
  tile.append(icon(spec.symbol, spec.kind === "brand" ? "icon icon-brand" : "icon"));
  return tile;
}

// A settings row. `path` (e.g. "display.volume") lets the app mark unsaved rows.
export function row(title, hint, controls = [], { path, icon: ico, app, onFocus } = {}) {
  return h("div", { class: "row", "data-path": path, onFocusin: onFocus, onPointerdown: onFocus },
    app ? appIcon(app) : ico && h("span", { class: "row-icon" }, icon(ico)),
    h("div", { class: "row-text" },
      h("div", { class: "row-title" }, title),
      hint && h("div", { class: `row-hint${hint.warn ? " warn" : ""}`, title: hint.title }, hint.text ?? hint)),
    h("div", { class: "row-control" }, ...[controls].flat()));
}

